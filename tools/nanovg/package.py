#!/usr/bin/env python3
"""Build an opt-in launcher component; never changes the standard launcher.
Run build.py first. Does not install, deploy, or rewrite a boot trigger.
"""
from pathlib import Path
import json
import sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from payload_menu import LAUNCHER_SCRIPTS,system_package
from send_app import build_payload
from package_payload import wire_json

from civapps_native_ui import verify
SCRIPTS=[ROOT/'app/vendor/native-ui-runtime.js',ROOT/'app/src/nanovg/resident-ui.js']

def build():
    verify(ROOT)
    for p in SCRIPTS+LAUNCHER_SCRIPTS:
        if not p.is_file(): raise ValueError(f'Missing runtime dependency: {p}')
    # app.js must remain last: resident evaluate() expects the launcher factory.
    source=build_payload(SCRIPTS+LAUNCHER_SCRIPTS[:-1]).decode()+'\n;CivNanoVGPrototype.enabled=true;window.__civNanoVGNextMount=true;\n'+LAUNCHER_SCRIPTS[-1].read_text()
    p=system_package('launcher',source,'0.4.3-nanovg.14')
    out=ROOT/'dist/launcher-nanovg.civupdate';out.parent.mkdir(exist_ok=True);out.write_bytes(wire_json(p)+b'\n')
    (ROOT/'dist/launcher-nanovg.js').write_text(source)
    # Inspect the exact freshly generated bytes and source order/checksum.
    actual=json.loads(out.read_bytes());assert actual==p;assert system_package('launcher',actual['source'],actual['release'])==actual
    html=(ROOT/'app/index.html').read_text()
    tags=''.join('<script src="'+str(path.relative_to(ROOT/'app'))+'"></script>' for path in SCRIPTS)
    tags+='<script>CivNanoVGPrototype.enabled=true;window.__civNanoVGNextMount=true;</script>'
    html=html.replace('<script src="app.js">',tags+'<script src="app.js">')
    shell=html.replace('<script src="boot.js">','<script>CivHomebrewNativeUI.start({browser:true}).catch(console.error);</script><script src="boot.js">')
    (ROOT/'app/nanovg-terminal.html').write_text(shell)
    (ROOT/'app/nanovg.html').write_text(html)
    print(f'Built and inspected {out}: {len(out.read_bytes()):,} bytes; {len(SCRIPTS)+len(LAUNCHER_SCRIPTS)} ordered scripts; app.js last')
    print('Browser preview: app/nanovg.html?demo=1 (separate from native qualification)')
if __name__=='__main__': build()
